-- number. Every statement is safe to re-run (auto-migrate retries a file
-- whose statement failed on the next boot).
ALTER TYPE "public"."email_automation_type" ADD VALUE IF NOT EXISTS 'order_confirmation';--> statement-breakpoint
ALTER TYPE "public"."email_automation_type" ADD VALUE IF NOT EXISTS 'order_admin_notification';--> statement-breakpoint
