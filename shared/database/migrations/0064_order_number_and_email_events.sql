-- order.order_number (#10001, #10002, …). The drizzle-generated form —
-- ADD COLUMN … GENERATED BY DEFAULT AS IDENTITY — would number existing
-- orders in physical row order, so instead, in ONE statement (one
-- transaction, holding the table lock throughout so no order can be inserted
-- half-way): add the column, backfill existing orders in placement order
-- (created_at, then id) from 10001, then turn it into an identity column
-- whose sequence continues after the highest number. Orders inserted after
-- this commits get their number from the identity default.
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_schema = 'public' AND table_name = 'order' AND column_name = 'order_number'
  ) THEN
    ALTER TABLE "order" ADD COLUMN "order_number" integer;
  END IF;

  LOCK TABLE "order" IN SHARE ROW EXCLUSIVE MODE;

  UPDATE "order" AS o
  SET "order_number" = n.num
  FROM (
    SELECT
      "id",
      (SELECT COALESCE(MAX("order_number"), 10000) FROM "order")
        + ROW_NUMBER() OVER (ORDER BY "created_at", "id") AS num
    FROM "order"
    WHERE "order_number" IS NULL
  ) AS n
  WHERE o."id" = n."id";

  IF NOT EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_schema = 'public' AND table_name = 'order'
      AND column_name = 'order_number' AND is_identity = 'YES'
  ) THEN
    ALTER TABLE "order" ALTER COLUMN "order_number" SET NOT NULL;
    ALTER TABLE "order" ALTER COLUMN "order_number"
      ADD GENERATED BY DEFAULT AS IDENTITY (SEQUENCE NAME "order_order_number_seq" START WITH 10001);
  END IF;

  PERFORM setval(
    pg_get_serial_sequence('"order"', 'order_number'),
    GREATEST(COALESCE((SELECT MAX("order_number") FROM "order"), 10000), 10000)
  );
END $$;--> statement-breakpoint
CREATE UNIQUE INDEX IF NOT EXISTS "order_order_number_idx" ON "order" USING btree ("order_number");
